"""The morphological evidence that the wrist channel is inverted.

`figures/gate2_polarity.png` was committed in September without a script, which
broke the repo's rule that every figure is regenerated by one. This module
reproduces it, and replaces eyeballing with a measurement.

On conventional PPG an ECG R-peak is followed by an upward systolic rise. The
test is a **beat-triggered average**: take every ECG beat that falls in a
sitting window, align the filtered wrist signal on it, normalise each segment
and average. If the channel is inverted the dominant excursion after a beat is
a trough rather than a peak.

Sitting only, because it is the quietest activity and motion artefact would
otherwise dominate. The average is cached, since it costs one pass over all
fifteen pickles.

Run with ``python -m src.figures_polarity``.
"""

from __future__ import annotations

from pathlib import Path

import textwrap

import numpy as np
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from src.data import WRIST_BVP_HZ, available_subjects, load_subject  # noqa: E402
from src.measure_quality import FIGURES, RESULTS  # noqa: E402
from src.preprocess import WINDOW_SECONDS, filter_signal, segment  # noqa: E402

CACHE = RESULTS / "beat_triggered_average.npz"
SUBJECT = "S2"          # the panel subject, chosen in September; kept for continuity
SITTING = 1
CHEST_HZ = 700
PRE_S, POST_S = 0.2, 0.9
PRE, POST = int(PRE_S * WRIST_BVP_HZ), int(POST_S * WRIST_BVP_HZ)


def sitting_beats(data: dict, filtered: np.ndarray) -> np.ndarray:
    """ECG beat times, in seconds, that fall inside a sitting period."""
    activity = np.asarray(data["activity"]).ravel().astype(int)
    beats = np.asarray(data["rpeaks"]).ravel() / CHEST_HZ
    act_hz = len(activity) / (len(filtered) / WRIST_BVP_HZ)
    index = np.clip((beats * act_hz).astype(int), 0, len(activity) - 1)
    return beats[activity[index] == SITTING]


def beat_triggered(filtered: np.ndarray, beats: np.ndarray) -> tuple[np.ndarray, int]:
    """Mean of the normalised wrist signal around each beat."""
    segments = []
    for beat in beats:
        i = int(beat * WRIST_BVP_HZ)
        if i - PRE < 0 or i + POST >= len(filtered):
            continue
        s = filtered[i - PRE:i + POST]
        segments.append((s - s.mean()) / (s.std() + 1e-12))
    stack = np.asarray(segments)
    return stack.mean(axis=0), len(stack)


def compute() -> dict[str, np.ndarray]:
    """One pass over every subject. Cached, because it reads 20 GB of pickles."""
    if CACHE.exists():
        with np.load(CACHE) as cached:
            return {k: cached[k] for k in cached.files}
    out: dict[str, np.ndarray] = {}
    for subject in available_subjects():
        data = load_subject(subject)
        filtered = filter_signal(np.asarray(data["signal"]["wrist"]["BVP"]).ravel())
        average, n = beat_triggered(filtered, sitting_beats(data, filtered))
        out[subject] = average
        out[f"{subject}_n"] = np.array(n)
        print(f"  {subject:4s} {n:5d} sitting beats", flush=True)
        del data, filtered
    RESULTS.mkdir(exist_ok=True)
    np.savez(CACHE, **out)
    return out


def main() -> None:
    FIGURES.mkdir(exist_ok=True)
    averages = compute()
    subjects = available_subjects()
    t = np.arange(-PRE, POST) / WRIST_BVP_HZ
    after = t >= 0

    # The claim, as a number: is the dominant post-beat excursion downward?
    depth = {s: float(averages[s][after].min()) for s in subjects}
    height = {s: float(averages[s][after].max()) for s in subjects}
    latency = {s: float(t[after][averages[s][after].argmin()]) for s in subjects}
    inverted = [s for s in subjects if abs(depth[s]) > height[s]]

    fig = plt.figure(figsize=(16, 9.6))
    grid = fig.add_gridspec(2, 3, height_ratios=[1, 1.15], hspace=0.42, wspace=0.26)

    # Top row: three example windows, so the shape is visible and not only summarised.
    data = load_subject(SUBJECT)
    raw = np.asarray(data["signal"]["wrist"]["BVP"]).ravel()
    windows, starts = segment(filter_signal(raw))
    activity = np.asarray(data["activity"]).ravel().astype(int)
    act_hz = len(activity) / (len(raw) / WRIST_BVP_HZ)
    codes = np.array([activity[min(int(s * act_hz), len(activity) - 1)] for s in starts])
    candidates = np.flatnonzero(codes == SITTING)
    beats_s = np.asarray(data["rpeaks"]).ravel() / CHEST_HZ
    for col, w in enumerate(candidates[np.linspace(0, len(candidates) - 1, 3).astype(int)]):
        ax = fig.add_subplot(grid[0, col])
        body, t0 = windows[w], starts[w]
        ax.plot(np.arange(len(body)) / WRIST_BVP_HZ, body, color="#2c5f8a", lw=1.3)
        for b in beats_s[(beats_s >= t0) & (beats_s < t0 + WINDOW_SECONDS)] - t0:
            ax.axvline(b, color="#b23a48", lw=0.9, alpha=0.75)
        ax.set_xlim(0, WINDOW_SECONDS)
        ax.set_xlabel("seconds within the window", fontsize=9)
        ax.tick_params(labelsize=8)
        ax.set_title(f"{SUBJECT} window {w}, sitting", fontsize=10)
        if col == 0:
            ax.set_ylabel("filtered wrist BVP", fontsize=9)

    # Bottom left: the beat-triggered average for every subject.
    ax = fig.add_subplot(grid[1, :2])
    for s in subjects:
        ax.plot(t * 1000, averages[s], color="#9bb4cc", lw=1)
    mean = np.mean([averages[s] for s in subjects], axis=0)
    ax.plot(t * 1000, mean, color="#2c5f8a", lw=2.6, label="mean of all 15 subjects")
    ax.axvline(0, color="#b23a48", lw=1.4, label="ECG R-peak")
    ax.axhline(0, color="#999", lw=0.8, ls=":")
    ax.set_xlabel("milliseconds from the ECG beat", fontsize=9.5)
    ax.set_ylabel("normalised wrist signal", fontsize=9.5)
    ax.legend(fontsize=9, loc="upper right")
    ax.set_title("Every subject dips after a beat, where conventional PPG rises",
                 fontsize=11, loc="left")
    ax.text(0, -0.235, "Thin lines are individual subjects. The window spans roughly one "
            "cardiac cycle at a resting heart rate, so where each curve reaches its\n"
            "minimum is not a pulse transit time and is not interpreted as one. The "
            "evidence is the asymmetry, not the phase.", transform=ax.transAxes,
            fontsize=8.5, color="#555", va="top")

    # Bottom right: trough against peak, one point per subject.
    ax2 = fig.add_subplot(grid[1, 2])
    ax2.scatter([height[s] for s in subjects], [abs(depth[s]) for s in subjects],
                s=70, color="#2c5f8a", alpha=0.85)
    lim = max(max(height.values()), max(abs(v) for v in depth.values())) * 1.15
    ax2.plot([0, lim], [0, lim], color="#999", ls="--", lw=1)
    ax2.text(lim * 0.06, lim * 0.9, "fall deeper\nthan rise", fontsize=8.5, color="#2c5f8a")
    ax2.text(lim * 0.62, lim * 0.3, "conventional\nPPG would\nland here", fontsize=8.5,
             color="#b23a48")
    for s in subjects:
        ax2.annotate(s, (height[s], abs(depth[s])), fontsize=7.5,
                     xytext=(4, 3), textcoords="offset points")
    ax2.set_xlim(0, lim); ax2.set_ylim(0, lim)
    ax2.set_xlabel("largest rise after a beat", fontsize=9.5)
    ax2.set_ylabel("largest fall after a beat", fontsize=9.5)
    ax2.set_title(f"{len(inverted)} of 15 fall further than they rise", fontsize=11, loc="left")

    lat = np.array(list(latency.values())) * 1000
    beats = int(sum(averages[f"{s}_n"] for s in subjects))
    margin = np.median([abs(depth[s]) - height[s] for s in subjects])
    caption = textwrap.fill(
        f"Beat-triggered average over sitting windows, {beats:,} beats. Segments are "
        f"normalised before averaging, so this measures pulse shape, not size. On all "
        f"fifteen subjects the fall after a beat exceeds the rise, by a median of "
        f"{margin:.2f} standard deviations. Conventional PPG has the sharp excursion "
        f"upward.", 165)
    fig.suptitle(
        "The wrist channel is inverted: the sharp excursion after an ECG beat is downward\n"
        + caption, fontsize=11.5, y=0.995, va="top")
    fig.tight_layout(rect=(0, 0, 1, 0.855))
    fig.savefig(FIGURES / "gate2_polarity.png", dpi=150)
    plt.close(fig)

    print(f"\n  inverted (fall deeper than rise): {len(inverted)}/15 -> {inverted}")
    print(f"  trough latency {lat.min():.0f} to {lat.max():.0f} ms, median {np.median(lat):.0f}")
    for s in subjects:
        print(f"    {s:4s} fall {depth[s]:+.2f}  rise {height[s]:+.2f}  "
              f"latency {latency[s]*1000:+4.0f} ms  {'inverted' if abs(depth[s])>height[s] else 'NOT'}")
    print("  figures/gate2_polarity.png")


if __name__ == "__main__":
    main()
