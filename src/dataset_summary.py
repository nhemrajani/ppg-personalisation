"""A subject-by-subject summary of PPG-DaLiA, for the appendix.

Every number here is read from the dataset files on this machine, at
data/PPG_FieldStudy/, extracted from the archive downloaded from the UCI
repository. Nothing is copied from the dataset's documentation or from any
paper: demographics come from each subject's questionnaire inside the pickle,
durations from the wrist signal itself, heart rate from the supplied labels,
and signal quality from our own measurements.

Writes results/subject_summary.csv and docs/appendix-dataset.md.
"""

from __future__ import annotations

import csv
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from src.data import DATA_DIR, WRIST_ACC_HZ, WRIST_BVP_HZ, available_subjects, load_subject, subject_path
from src.harness import load as load_experiments
from src.measure_quality import ACTIVITY_NAMES
from src.preprocess import SHIFT_SECONDS, WINDOW_SECONDS

ROOT = Path(__file__).resolve().parent.parent
CHEST_HZ = 700
FITNESS = {1: "less than monthly", 2: "monthly", 3: "weekly", 4: "2-3 a week",
           5: "3-5 a week", 6: "5-7 a week"}


def file_fingerprint(path: Path, chunk: int = 1 << 20) -> str:
    """First and last megabyte, enough to identify the file without reading 1.4 GB."""
    size = path.stat().st_size
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        digest.update(handle.read(chunk))
        if size > chunk * 2:
            handle.seek(-chunk, 2)
            digest.update(handle.read(chunk))
    return digest.hexdigest()[:12]


def summarise_subject(subject: str, quality: dict, arm_a: dict) -> dict:
    data = load_subject(subject)
    quest = data["questionnaire"]
    bvp = np.asarray(data["signal"]["wrist"]["BVP"]).ravel()
    hr = np.asarray(data["label"]).ravel()
    path = subject_path(subject)

    mask = quality["subject"] == int(subject[1:])
    activity = quality["activity"][mask].astype(int)
    counts = {code: int((activity == code).sum()) for code in ACTIVITY_NAMES}

    return {
        "subject": subject,
        "age": int(quest["AGE"]),
        "sex": str(quest["Gender"]).strip().upper(),
        "height_cm": float(quest["HEIGHT"]),
        "weight_kg": float(quest["WEIGHT"]),
        "bmi": round(float(quest["WEIGHT"]) / (float(quest["HEIGHT"]) / 100) ** 2, 1),
        "fitzpatrick_skin_type": int(quest["SKIN"]),
        "fitness_level": int(quest["SPORT"]),
        "fitness_meaning": FITNESS.get(int(quest["SPORT"]), "?"),
        "duration_min": round(len(bvp) / WRIST_BVP_HZ / 60, 1),
        "windows": len(hr),
        "hr_min": round(float(hr.min()), 1),
        "hr_median": round(float(np.median(hr)), 1),
        "hr_max": round(float(hr.max()), 1),
        "hr_iqr": round(float(np.percentile(hr, 75) - np.percentile(hr, 25)), 1),
        "pct_hr_outside_60_150": round(float(np.mean((hr < 60) | (hr > 150)) * 100), 1),
        "activities_present": sum(1 for c, n in counts.items() if n and c != 0),
        "windows_rejected": 0,
        "median_sqi": round(float(np.median(quality["sqi"][mask])), 3),
        "windows_over_10_iqr": int(np.nansum(quality["spike"][mask] > 10)) if "spike" in quality else None,
        "arm_a_mae_papagei_p": arm_a.get(("p", int(subject[1:]))),
        "arm_a_mae_papagei_s": arm_a.get(("s", int(subject[1:]))),
        **{f"min_{ACTIVITY_NAMES[c].replace(' ', '_')}": round(n * SHIFT_SECONDS / 60, 1)
           for c, n in counts.items()},
        "file": path.name,
        "file_mb": round(path.stat().st_size / 1e6),
        "fingerprint": file_fingerprint(path),
    }


def main() -> None:
    subjects = available_subjects()
    if not subjects:
        raise SystemExit("No subjects found. Unzip PPG-DaLiA into data/ first.")

    with np.load(ROOT / "results" / "quality_windows.npz") as q:
        quality = {k: q[k] for k in q.files}
    spikes = ROOT / "results" / "spike_audit.csv"
    arm_a = {
        (r["backbone"], int(r["subject"])): round(float(r["mae"]), 2)
        for r in load_experiments()
        if r["arm"] == "A" and r["polarity"] == "asis"
    }

    rows = [summarise_subject(s, quality, arm_a) for s in subjects]
    out_csv = ROOT / "results" / "subject_summary.csv"
    with open(out_csv, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {out_csv}")

    write_appendix(rows, spikes)


def write_appendix(rows: list[dict], spikes: Path) -> None:
    total_windows = sum(r["windows"] for r in rows)
    total_hours = sum(r["duration_min"] for r in rows) / 60
    lines: list[str] = []
    add = lines.append

    add("# Appendix: The PPG-DaLiA Dataset, Subject by Subject\n")
    add("Generated by `python -m src.dataset_summary` from the dataset files held locally at")
    add(f"`data/PPG_FieldStudy/`. Every value is measured from those files rather than quoted")
    add("from the dataset documentation or from any publication. Demographics come from each")
    add("subject's questionnaire inside the pickle, durations from the wrist signal, heart rate")
    add("from the supplied labels, and signal quality from our own measurements.\n")
    add(f"Generated {datetime.now(timezone.utc).strftime('%d %B %Y')}. "
        f"Fifteen subjects, {total_windows:,} analysis windows, {total_hours:.1f} hours of recording.\n")

    add("## Subjects\n")
    add("| Subject | Age | Sex | Height (cm) | Weight (kg) | BMI | Fitzpatrick | Fitness |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in rows:
        add(f"| {r['subject']} | {r['age']} | {r['sex']} | {r['height_cm']:.0f} | {r['weight_kg']:.0f} "
            f"| {r['bmi']} | {r['fitzpatrick_skin_type']} | {r['fitness_level']} ({r['fitness_meaning']}) |")

    ages = np.array([r["age"] for r in rows])
    skins = [r["fitzpatrick_skin_type"] for r in rows]
    add(f"\nAge {ages.min()} to {ages.max()}, mean {ages.mean():.1f}. "
        f"Sex: {sum(1 for r in rows if r['sex'].startswith('F'))} female, "
        f"{sum(1 for r in rows if r['sex'].startswith('M'))} male. "
        f"Fitzpatrick skin type {min(skins)} to {max(skins)}, "
        f"distribution {dict(sorted({s: skins.count(s) for s in set(skins)}.items()))}. "
        "The scale runs 1 to 6; the darker end is not represented, which is why any "
        "analysis by skin type in this study is illustrative only.\n")

    add("## Recording and heart rate\n")
    add("| Subject | Duration (min) | Windows | HR min | HR median | HR max | HR IQR | % outside 60-150 |")
    add("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for r in rows:
        add(f"| {r['subject']} | {r['duration_min']} | {r['windows']:,} | {r['hr_min']:.0f} "
            f"| {r['hr_median']:.0f} | {r['hr_max']:.0f} | {r['hr_iqr']:.0f} | {r['pct_hr_outside_60_150']} |")
    add("\nWindows are 8 seconds on a 2-second shift, matching the grid the dataset's own heart-rate")
    add("labels are defined on, so the window count equals the label count for every subject.")
    add("S6 is short because of a documented hardware failure during collection; the file contains")
    add("only the valid portion, about the first 1.5 hours.\n")

    add("## Minutes recorded per activity\n")
    names = [ACTIVITY_NAMES[c] for c in sorted(ACTIVITY_NAMES)]
    add("| Subject | " + " | ".join(n.title() for n in names) + " |")
    add("| --- " * (len(names) + 1) + "|")
    for r in rows:
        cells = [f"{r['min_' + n.replace(' ', '_')]:.0f}" if r.get('min_' + n.replace(' ', '_')) else "-"
                 for n in names]
        add(f"| {r['subject']} | " + " | ".join(cells) + " |")
    add("\nActivity 0 is the transient period between activities, which the dataset labels")
    add("explicitly. It is the second largest category overall and is treated as a stratum like")
    add("any other in the splitting protocol. S6 has no lunch, walking or working because")
    add("collection stopped before those activities began.\n")

    add("## Signal quality and per-subject difficulty\n")
    add("| Subject | Windows rejected | Median SQI | Arm A MAE, PaPaGei-P | Arm A MAE, PaPaGei-S |")
    add("| --- | --- | --- | --- | --- |")
    for r in rows:
        add(f"| {r['subject']} | {r['windows_rejected']} | {r['median_sqi']:+.2f} "
            f"| {r['arm_a_mae_papagei_p'] or '-'} | {r['arm_a_mae_papagei_s'] or '-'} |")
    add("\nNo window is rejected for any subject. PaPaGei's flatline test compares consecutive-sample")
    add("changes against an absolute threshold of 0.01 while the median step in this signal is 4.84")
    add("units, so the test cannot fire here. The signal quality index is PaPaGei's own measure,")
    add("the skewness of the window; on this dataset its sign is inverted relative to convention")
    add("because the Empatica BVP waveform runs downward, so more negative means cleaner.")
    add("Arm A is the unadapted population model under leave-one-subject-out, and is included here")
    add("because per-subject difficulty varies far more than the aggregate suggests.\n")

    add("## Provenance\n")
    add("| Subject | File | Size (MB) | Fingerprint |")
    add("| --- | --- | --- | --- |")
    for r in rows:
        add(f"| {r['subject']} | `{r['file']}` | {r['file_mb']:,} | `{r['fingerprint']}` |")
    add("\nThe fingerprint is a SHA-256 over the first and last megabyte of each file, which")
    add("identifies it without hashing 1.4 GB. Files were obtained from the UCI Machine Learning")
    add("Repository and are not redistributed in this repository.")

    out = ROOT / "docs" / "appendix-dataset.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
